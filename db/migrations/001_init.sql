-- Emails are stored lowercase, so "Bob@X.com" and "bob@x.com" are one account:
-- the API lowercases them and the unique constraint rejects the second signup.
create table users (
  id            serial primary key,
  email         text not null unique check (email = lower(email) and email like '%_@_%'),
  -- Never a plain password: only the "scrypt$salt$hash" format is accepted.
  password_hash text not null check (password_hash like 'scrypt$%'),
  created_at    timestamptz not null default now()
);

-- The cookie holds a random token; only its SHA-256 is stored here,
-- so someone who reads the database cannot reuse a live session.
create table sessions (
  id         text primary key check (id ~ '^[0-9a-f]{64}$'),
  user_id    int  not null references users (id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  check (expires_at > created_at)
);

create table photos (
  id              serial primary key,
  -- No cascade: a user who uploaded photos cannot be deleted by accident.
  user_id         int  not null references users (id),
  -- Generated by the server (uuid + .jpg), so a key can never contain "../".
  storage_key     text not null unique check (storage_key ~ '^[0-9a-f-]{36}\.jpg$'),
  -- Fingerprint of the file's bytes: the same file cannot be uploaded twice.
  sha256          text not null unique check (sha256 ~ '^[0-9a-f]{64}$'),
  original_name   text not null check (char_length(original_name) between 1 and 255),
  lat             double precision not null check (lat between -90 and 90),
  lng             double precision not null check (lng between -180 and 180),
  -- 'exif': read from the photo's GPS; 'manual': placed by the user.
  location_source text not null check (location_source in ('exif', 'manual')),
  description     text check (char_length(description) <= 2000),
  created_at      timestamptz not null default now(),
  -- Devices write 0,0 when they had no GPS fix: it means "no position".
  check (not (lat = 0 and lng = 0))
);

create table comments (
  id         serial primary key,
  photo_id   int  not null references photos (id) on delete cascade,
  user_id    int  not null references users (id),
  -- Stored trimmed, never empty, at most 1000 characters.
  body       text not null check (body = btrim(body) and char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);

-- The side panel loads the comments of one photo, oldest first.
create index comments_photo_idx on comments (photo_id, created_at);
